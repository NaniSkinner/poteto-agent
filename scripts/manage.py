#!/usr/bin/env python3
"""Render/check a local candidate only. Python 3.11+; no installation commands."""
import argparse
import json
from pathlib import Path
import tomllib


def target(source):
    return Path(source) / 'codex/workflow-advisor.toml'


def profile_text(source):
    source = Path(source).resolve(strict=True)
    contract = source / 'poteto-advisor/references/contract.md'
    instructions = (
        f'You are Poteto, role workflow-advisor. Source package: {source}. '
        f'Read {source / "poteto-advisor/SKILL.md"} and applicable references before work. '
        'The canonical mandatory contract follows.\n\n' + contract.read_text(encoding='utf-8')
    )
    result = ('# Local Poteto candidate; generated by scripts/manage.py\n'
              'name = "workflow-advisor"\n'
              'description = "Poteto: evidence-grounded agent workflow advisor; not a general developer or repository auditor."\n'
              'developer_instructions = ' + json.dumps(instructions, ensure_ascii=False) + '\n')
    tomllib.loads(result)
    return result


def safe_target(source):
    source = Path(source).resolve(strict=True)
    p = target(source)
    if p.parent.is_symlink() or p.is_symlink():
        raise ValueError('Refusing linked candidate destination')
    return source, p


def render(source):
    source, p = safe_target(source)
    expected = profile_text(source)
    if p.exists():
        if p.read_text(encoding='utf-8') != expected:
            raise ValueError('Existing candidate differs; refusing overwrite (including drift). Reconcile manually.')
        return p
    p.parent.mkdir(exist_ok=True)
    with p.open('x', encoding='utf-8') as stream:
        stream.write(expected)
    return p


def check(source):
    source, p = safe_target(source)
    if not p.is_file():
        raise ValueError('Candidate missing')
    if p.read_text(encoding='utf-8') != profile_text(source):
        raise ValueError('Profile/contract drift')
    return p


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('action', choices=('render', 'check'))
    parser.add_argument('--source', type=Path, default=Path(__file__).resolve().parents[1])
    args = parser.parse_args()
    try:
        print((render if args.action == 'render' else check)(args.source))
    except (ValueError, OSError) as exc:
        parser.exit(1, f'{exc}\n')

if __name__ == '__main__':
    main()
